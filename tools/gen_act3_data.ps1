# 3막(21~30장) 잡몹 40종 데이터 생성기 -> test/assets/js/act3_data.js
# (원 지시서의 tools/gen_act3_data.py 와 같은 일. 이 PC 에 Python 이 없어서 PowerShell 판)
# 사용: pwsh -File tools/gen_act3_data.ps1 [-Manifest tools/mobs_21_to_30_manifest.json] [-Out test/assets/js/act3_data.js]
param(
  [string]$Manifest = (Join-Path $PSScriptRoot 'mobs_21_to_30_manifest.json'),
  [string]$Out = (Join-Path $PSScriptRoot '..\test\assets\js\act3_data.js')
)
$man = Get-Content -LiteralPath $Manifest -Raw -Encoding utf8 | ConvertFrom-Json
$ROLE = @{ '근접' = 'MELEE'; '원거리' = 'RANGED'; '돌진' = 'CHARGER'; '정예' = 'MELEE_HEAVY' }
$mobs = [ordered]@{}
$rows = [ordered]@{}
foreach ($n in 21..30) { $rows["$n"] = [System.Collections.ArrayList]::new() }
foreach ($m in $man.mobs) {
  $frames = @($m.frames | Sort-Object i | ForEach-Object { , @([int]$_.ax, [int]$_.ay, [int]$_.bodyH, [int]$_.bodyW) })
  if ($frames.Count -ne 16) { throw "$($m.id): frames $($frames.Count) (16 이어야 함)" }
  $mobs[$m.id] = [ordered]@{ f = $m.file; n = $m.name_ko; h = [int]$m.suggest_h; a = $frames }
  $type = $ROLE[$m.role]; if (-not $type) { throw "$($m.id): 모르는 role $($m.role)" }   # ($role 은 $ROLE 과 같은 변수라 쓰면 안 됨)
  [void]$rows["$($m.chapter)"].Add(@($m.id, [int]$m.no, $m.name_ko, $type, $(if ($m.elite) { 1 } else { 0 })))
}
$js = '/* generated by tools/gen_act3_data.ps1 from mobs_21_to_30_manifest.json. Do not edit by hand. */' + "`n" +
  'window.ACT3_MOBS=' + ($mobs | ConvertTo-Json -Compress -Depth 6) + ";`n" +
  'window.ACT3_MOB_ROWS=' + ($rows | ConvertTo-Json -Compress -Depth 6) + ";`n"
New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
[IO.File]::WriteAllText([IO.Path]::GetFullPath($Out), $js, [Text.UTF8Encoding]::new($false))
Write-Host ("act3_data.js: {0} mobs, {1} bytes -> {2}" -f $mobs.Count, $js.Length, $Out)
